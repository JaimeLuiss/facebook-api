        <h1 id="introduction">Introduction</h1>
<p>API REST de publicaciones, autenticación, comentarios y likes.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost</code>
</aside>
<pre><code>Documentación de la API REST de publicaciones. Los endpoints actuales están disponibles bajo `/api/v1`.

Los endpoints protegidos requieren el token Bearer devuelto por `/api/v1/register` o `/api/v1/login`.</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer Bearer {TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Usa el token recibido al registrarte o iniciar sesión como <code>Authorization: Bearer {token}</code>.</p>

